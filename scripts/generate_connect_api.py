#!/usr/bin/env python3
"""Generate the supported Connect operations from Apple's OpenAPI 4.5.1."""
import json
import pathlib
import re
import subprocess
import sys
from generate_models import ROOT, CONNECT_PATHS

spec=json.loads(pathlib.Path(sys.argv[1]).read_text())
assert spec['info']['version']=='4.5.1'
resources={
 'apps':('App','Apps'), 'builds':('Build','Builds'), 'buildUploads':('BuildUpload','BuildUploads'),
 'buildUploadFiles':('BuildUploadFile','BuildUploadFiles'), 'inAppPurchasesV2':('InAppPurchase','InAppPurchases'),
 'inAppPurchaseLocalizations':('InAppPurchaseLocalization','InAppPurchaseLocalizations'),
 'inAppPurchaseAvailabilities':('InAppPurchaseAvailability','InAppPurchaseAvailabilities'),
 'inAppPurchasePriceSchedules':('InAppPurchasePriceSchedule','InAppPurchasePriceSchedules'),
 'subscriptionGroups':('SubscriptionGroup','SubscriptionGroups'),
 'subscriptionGroupLocalizations':('SubscriptionGroupLocalization','SubscriptionGroupLocalizations'),
 'subscriptions':('Subscription','Subscriptions'), 'subscriptionLocalizations':('SubscriptionLocalization','SubscriptionLocalizations'),
 'subscriptionAvailabilities':('SubscriptionAvailability','SubscriptionAvailabilities'),
 'subscriptionPrices':('SubscriptionPrice','SubscriptionPrices'), 'territories':('Territory','Territories'),
}
related={
 '/v1/apps/{id}/inAppPurchasesV2':'ListAppInAppPurchases',
 '/v1/apps/{id}/subscriptionGroups':'ListAppSubscriptionGroups',
 '/v1/apps/{id}/buildUploads':'ListAppBuildUploads',
 '/v1/buildUploads/{id}/buildUploadFiles':'ListBuildUploadFiles',
 '/v2/inAppPurchases/{id}/inAppPurchaseLocalizations':'ListInAppPurchaseLocalizations',
 '/v2/inAppPurchases/{id}/pricePoints':'ListInAppPurchasePricePoints',
 '/v1/subscriptionGroups/{id}/subscriptions':'ListGroupSubscriptions',
 '/v1/subscriptions/{id}/subscriptionLocalizations':'ListSubscriptionLocalizations',
 '/v1/subscriptions/{id}/pricePoints':'ListSubscriptionPricePoints',
 '/v1/subscriptions/{id}/prices':'ListSubscriptionPrices',
}
out=['// Code generated by scripts/generate_connect_api.py; DO NOT EDIT.',
     '// App Store Connect OpenAPI 4.5.1.', 'package appstoreconnect',
     'import ("context"; "net/url"; "github.com/sunbeam27/app-store/appstoreconnect/model")']
coverage=[]
for path in CONNECT_PATHS:
 for verb,op in spec['paths'][path].items():
    if verb not in ('get','post','patch','delete'):continue
    singular,plural=resources[op['operationId'].split('_')[0]]
    if path in related:method=related[path]
    else:method={'get':('Get'+singular if '{id}' in path else 'List'+plural),'post':'Create'+singular,'patch':'Update'+singular,'delete':'Delete'+singular}[verb]
    if path=='/v1/buildUploadFiles/{id}' and verb=='patch':method='CommitBuildUploadFile'
    request=op.get('requestBody',{}).get('content',{}).get('application/json',{}).get('schema',{}).get('$ref','').split('/')[-1]
    response=None
    for status,r in op['responses'].items():
        if status.startswith('2'):
            ref=r.get('content',{}).get('application/json',{}).get('schema',{}).get('$ref')
            if ref:response=ref.split('/')[-1]
    params=['ctx context.Context'];expr=json.dumps(path)
    if '{id}' in path:
        params.append('id string');expr=expr.replace('{id}','"+url.PathEscape(id)+"')
    if request:params.append('request model.'+request)
    if verb=='get':params.append('query url.Values')
    q='query' if verb=='get' else 'nil';body='request' if request else 'nil'
    if response:
        out.append(f'func (c *Client) {method}({", ".join(params)}) (*model.{response},error) {{var response model.{response};if err:=c.Do(ctx,"{verb.upper()}",{expr},{q},{body},&response);err!=nil{{return nil,err}};return &response,nil}}')
    else:out.append(f'func (c *Client) {method}({", ".join(params)}) error {{return c.Do(ctx,"{verb.upper()}",{expr},{q},{body},nil)}}')
    coverage.append({'method':method,'httpMethod':verb.upper(),'path':path,'operationId':op['operationId'],'request':request or None,'response':response})
dest=ROOT/'appstoreconnect/api_generated.go';dest.write_text('\n'.join(out)+'\n')
subprocess.run(['gofmt','-w',str(dest)],check=True)
(ROOT/'appstoreconnect/api_coverage.json').write_text(json.dumps(coverage,indent=2)+'\n')
print('Generated',len(coverage),'Connect API operations')
