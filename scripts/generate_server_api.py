#!/usr/bin/env python3
"""Generate direct Server API methods from Apple Java v5.2.0 (local checkout)."""
import pathlib
import re
import subprocess
import sys

from generate_models import ROOT, SERVER_SHA, name

source=pathlib.Path(sys.argv[1])
assert subprocess.check_output(['git','-C',str(source),'rev-parse','HEAD'],text=True).strip()==SERVER_SHA
java=(source/'src/main/java/com/apple/itunes/storekit/client/BaseAppStoreServerAPIClient.java').read_text()
out=['// Code generated by scripts/generate_server_api.py; DO NOT EDIT.',
     '// Derived from Apple Java v5.2.0; see NOTICE.txt.', 'package appstoreserver',
     'import ("context"; "net/url"; "github.com/sunbeam27/app-store/appstoreserver/model")']
special={'getTransactionHistory','getAllSubscriptionStatuses','getRefundHistory','getNotificationHistory','uploadImage'}
operations=[]
for m in re.finditer(r'public\s+(\w+)\s+(\w+)\(([^)]*)\)\s+throws APIException, IOException\s*\{',java):
    ret,method,args=m.groups()
    start=m.end();end=start;depth=1
    while depth:
        if java[end]=='{':depth+=1
        if java[end]=='}':depth-=1
        end+=1
    body=java[start:end-1]
    if method in special:continue
    call=re.search(r'makeHttpCall\((.*?), "(\w+)", Map.of\(\), (\w+), (\w+)\.class, (\w+)\)',body)
    if not call:raise ValueError('Unrecognized method: '+method)
    expr,verb,payload,_,_=call.groups()
    params=['ctx context.Context']
    substitutions={}
    for arg in args.split(','):
        if not arg.strip():continue
        typ,identifier=arg.strip().split()
        goid=identifier[:1].lower()+name(identifier)[1:]
        # Keep conventional initialisms at the end of identifiers.
        goid=re.sub(r'Id$', 'ID', identifier)
        params.append(goid+' '+('string' if typ in ('String','UUID') else 'model.'+typ))
        substitutions[identifier]=goid
    for ident,goid in substitutions.items():
        expr=re.sub(r'\b'+ident+r'\b',lambda _: 'url.PathEscape('+goid+')' if ('string' in next(p for p in params if p.startswith(goid+' '))) else goid,expr)
    payload=substitutions.get(payload,payload)
    payload='nil' if payload=='null' else payload
    goname=name(method)
    if ret=='void':
        out.append(f'func (c *AppStoreServerAPIClient) {goname}({", ".join(params)}) error {{ return c.call(ctx,"{verb}",{expr},nil,{payload},nil) }}')
    else:
        out.append(f'func (c *AppStoreServerAPIClient) {goname}({", ".join(params)}) (*model.{ret},error) {{ var response model.{ret}; if err:=c.call(ctx,"{verb}",{expr},nil,{payload},&response);err!=nil {{return nil,err}};return &response,nil }}')
    operations.append({'method':goname,'httpMethod':verb,'pathExpression':call.group(1)})
dest=ROOT/'appstoreserver/api_generated.go';dest.write_text('\n'.join(out)+'\n')
subprocess.run(['gofmt','-w',str(dest)],check=True)
print('Generated',len(operations),'direct API methods; query/overload methods are in queries.go')
